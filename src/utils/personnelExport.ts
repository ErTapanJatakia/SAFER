/**
 * Creates a deep copy of a PersonnelRecord and applies redactions.
 * Any redacted field is replaced with "[REDACTED]".
 * The original record is guaranteed to remain untouched.
 */
export function applyRedactionsToPerson(person: PersonnelRecord, redactedKeys: Set<string>): PersonnelRecord {
  const isRosterRedacted = (subKey: string) => redactedKeys.has(subKey);

  const clone: PersonnelRecord = JSON.parse(JSON.stringify(person));

  // Top level fields
  if (redactedKeys.has('pmcEmployeeId')) {
    clone.pmcEmployeeId = '[REDACTED]';
    if (clone.demoId) clone.demoId = '[REDACTED]';
  }
  if (redactedKeys.has('badgeId')) clone.badgeId = '[REDACTED]';
  if (redactedKeys.has('fullName')) clone.fullName = '[REDACTED]';
  if (redactedKeys.has('displayName')) clone.displayName = '[REDACTED]';
  if (redactedKeys.has('callSign')) {
    clone.callSign = '[REDACTED]';
    if (clone.callsign) clone.callsign = '[REDACTED]';
  }
  if (redactedKeys.has('role')) {
    clone.role = '[REDACTED]';
    if (clone.roles) clone.roles = ['[REDACTED]'];
  }
  if (redactedKeys.has('specialisation')) {
    clone.specialisation = '[REDACTED]';
    if (clone.specialisations) clone.specialisations = ['[REDACTED]'];
  }
  if (redactedKeys.has('assignmentSector')) {
    clone.assignmentSector = '[REDACTED]' as any;
  }
  if (redactedKeys.has('contactEmail')) clone.contactEmail = '[REDACTED]';
  if (redactedKeys.has('personalEmail')) clone.personalEmail = '[REDACTED]';
  if (redactedKeys.has('birthDate')) clone.birthDate = '[REDACTED]';
  if (redactedKeys.has('maritalStatus')) clone.maritalStatus = '[REDACTED]' as any;
  if (redactedKeys.has('bloodGroup')) clone.bloodGroup = '[REDACTED]' as any;
  if (redactedKeys.has('bloodGroupDetails')) clone.bloodGroupDetails = '[REDACTED]';
  if (redactedKeys.has('healthParticulars')) clone.healthParticulars = '[REDACTED]';

  // Residence Address
  if (clone.residenceAddress) {
    if (redactedKeys.has('residenceAddress') || redactedKeys.has('residenceAddress.addressLine')) {
      clone.residenceAddress.addressLine = '[REDACTED]';
    }
    if (redactedKeys.has('residenceAddress') || redactedKeys.has('residenceAddress.city')) {
      clone.residenceAddress.city = '[REDACTED]';
    }
    if (redactedKeys.has('residenceAddress') || redactedKeys.has('residenceAddress.state')) {
      clone.residenceAddress.state = '[REDACTED]';
    }
    if (redactedKeys.has('residenceAddress') || redactedKeys.has('residenceAddress.postalCode')) {
      clone.residenceAddress.postalCode = '[REDACTED]';
    }
    if (redactedKeys.has('residenceAddress') || redactedKeys.has('residenceAddress.country')) {
      clone.residenceAddress.country = '[REDACTED]';
    }
  }

  // Correspondence Address
  if (clone.correspondenceAddress) {
    if (redactedKeys.has('correspondenceAddress') || redactedKeys.has('correspondenceAddress.addressLine')) {
      clone.correspondenceAddress.addressLine = '[REDACTED]';
    }
    if (redactedKeys.has('correspondenceAddress') || redactedKeys.has('correspondenceAddress.city')) {
      clone.correspondenceAddress.city = '[REDACTED]';
    }
    if (redactedKeys.has('correspondenceAddress') || redactedKeys.has('correspondenceAddress.state')) {
      clone.correspondenceAddress.state = '[REDACTED]';
    }
    if (redactedKeys.has('correspondenceAddress') || redactedKeys.has('correspondenceAddress.postalCode')) {
      clone.correspondenceAddress.postalCode = '[REDACTED]';
    }
    if (redactedKeys.has('correspondenceAddress') || redactedKeys.has('correspondenceAddress.country')) {
      clone.correspondenceAddress.country = '[REDACTED]';
    }
  }

  // Work Experience
  if (clone.workExperience && clone.workExperience.length > 0) {
    clone.workExperience = clone.workExperience.map((we, idx) => {
      const weCopy = { ...we };
      if (redactedKeys.has(`workExperience[${idx}].employerName`) || isRosterRedacted('workExperience.employerName')) {
        weCopy.employerName = '[REDACTED]';
      }
      if (redactedKeys.has(`workExperience[${idx}].employerAddress`) || isRosterRedacted('workExperience.employerAddress')) {
        weCopy.employerAddress = '[REDACTED]';
      }
      if (redactedKeys.has(`workExperience[${idx}].employerContactNumbers`) || isRosterRedacted('workExperience.employerContactNumbers')) {
        weCopy.employerContactNumbers = '[REDACTED]';
      }
      if (redactedKeys.has(`workExperience[${idx}].startDate`) || isRosterRedacted('workExperience.dates')) {
        weCopy.startDate = '[REDACTED]';
      }
      if (redactedKeys.has(`workExperience[${idx}].endDate`) || isRosterRedacted('workExperience.dates')) {
        weCopy.endDate = '[REDACTED]';
      }
      if (redactedKeys.has(`workExperience[${idx}].workDescription`) || isRosterRedacted('workExperience.descriptions')) {
        weCopy.workDescription = '[REDACTED]';
      }
      if (redactedKeys.has(`workExperience[${idx}].skillsInUse`) || isRosterRedacted('workExperience.descriptions')) {
        weCopy.skillsInUse = '[REDACTED]';
      }
      return weCopy;
    });
  }

  // Qualifications & Certifications
  if (clone.certifications && clone.certifications.length > 0) {
    clone.certifications = clone.certifications.map((cert, idx) => {
      const certCopy = { ...cert };
      if (redactedKeys.has(`certifications[${idx}].name`) || isRosterRedacted('certifications.names')) {
        certCopy.name = '[REDACTED]';
      }
      if (redactedKeys.has(`certifications[${idx}].completionDate`) || isRosterRedacted('certifications.dates')) {
        certCopy.completionDate = '[REDACTED]';
      }
      if (redactedKeys.has(`certifications[${idx}].expiryDate`) || isRosterRedacted('certifications.dates')) {
        certCopy.expiryDate = '[REDACTED]';
      }
      if (redactedKeys.has(`certifications[${idx}].issuer`) || isRosterRedacted('certifications.issuers')) {
        certCopy.issuer = '[REDACTED]';
      }
      if (redactedKeys.has(`certifications[${idx}].verificationId`) || isRosterRedacted('certifications.issuers')) {
        certCopy.verificationId = '[REDACTED]';
      }
      if (redactedKeys.has(`certifications[${idx}].verificationStatus`)) {
        certCopy.verificationStatus = '[REDACTED]' as any;
      }
      return certCopy;
    });
  }

  // Administrative Notes & Reviews
  if (redactedKeys.has('verificationStatus')) clone.verificationStatus = '[REDACTED]' as any;
  if (redactedKeys.has('outstandingRequirements')) {
    clone.outstandingRequirements = ['[REDACTED]'];
  }
  if (redactedKeys.has('administrativeNotes') || isRosterRedacted('administrativeNotes')) {
    clone.administrativeNotes = '[REDACTED]';
  }
  if (redactedKeys.has('notes') || isRosterRedacted('administrativeNotes')) {
    clone.notes = '[REDACTED]';
  }
  if (redactedKeys.has('lastSupervisorReviewDate') || isRosterRedacted('supervisorReview')) {
    clone.lastSupervisorReviewDate = '[REDACTED]';
  }
  if (redactedKeys.has('reviewedBy') || isRosterRedacted('supervisorReview')) {
    clone.reviewedBy = '[REDACTED]';
  }

  return clone;
}

/**
 * Builds a safe export filename based solely on identifier and date.
 * Strictly avoids personal emails, addresses, or health particulars.
 */
export function getSafeExportFilename(
  personOrList: PersonnelRecord | PersonnelRecord[],
  format: ExportFormat,
  dateStr: string = new Date().toISOString().slice(0, 10)
): string {
  const ext = format;
  if (Array.isArray(personOrList)) {
    return sanitizeSafeFilename(`personnel_roster_${personOrList.length}_records_${dateStr}.${ext}`);
  }
  const cleanId = (personOrList.pmcEmployeeId || personOrList.demoId || personOrList.badgeId || 'PERSONNEL')
    .replace(/[^a-zA-Z0-9_-]/g, '_');
  return sanitizeSafeFilename(`${cleanId}_personnel_record_${dateStr}.${ext}`);
}

